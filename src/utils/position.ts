interface GeneralPosition {
  companyName: string;
  companyLogo: string;
  propertyName: string;
  name: string;
  number: string;
  salary60: string;
  showSkillTags: {
    tag: string;
    highlightBackGroundColor?: string;
    highlightWordColor?: string;
  }[];
  workCity: string;
  publishTime: string;
  workingExp: string;
  education: string;
  workType: string;
  staffCard: {
    avatar: string;
    staffName: string;
    hrOnlineState: string;
  };
  skillLabel: {
    value: string;
    state: number;
  }[];
  jobSummary: string;
  // {"address":"北京 朝阳 大屯","companyName":"恒丰集团","locationType":"5","salary60":"8000-10000元"}
  cardCustomJson: string;
}

export function positionTransform(params: {
  detail: any;
  type: "boss" | "zhaopin";
}) {
  if (params.type === "boss") {
    return {
      jobSummary: "",
      propertyName: "",
      publishTime: "",
      ...params.detail,
      companyName: params.detail.brandName,
      companyLogo: params.detail.brandLogo,
      name: params.detail.jobName,
      number: params.detail.encryptJobId,
      salary60: params.detail.salaryDesc,
      showSkillTags: (params.detail.jobLabels || [])
        .concat(params.detail.skills)
        .filter((item: string) => !!item)
        .map((item: string) => ({
          tag: item,
          highlightBackGroundColor: "",
          highlightWordColor: "",
        })),
      workCity: params.detail.cityName,
      education: params.detail.jobDegree,
      workType: "全职",
      workingExp: params.detail.jobExperience,
      staffCard: {
        avatar: params.detail.bossAvatar,
        staffName: params.detail.bossName,
        hrOnlineState: params.detail.bossOnline ? "当前在线" : "当前离线",
      },
      skillLabel: params.detail.skills.map((item: string) => ({
        value: item,
        state: 0,
      })),
      // {"address":"北京 朝阳 大屯","companyName":"恒丰集团","locationType":"5","salary60":"8000-10000元"}
      cardCustomJson: JSON.stringify({
        address: [
          params.detail.cityName,
          params.detail.areaDistrict,
          params.detail.businessDistrict,
        ]
          .filter((item) => !!item)
          .join(" ")
          .trim(),
        companyName: params.detail.brandName,
        locationType: params.detail.jobType,
        salary60: params.detail.salaryDesc,
      }),
    };
  } else {
    return { ...params.detail };
  }
}
